import { describe, expect, it } from 'vitest'
import { advance, client, controlled, immediate, observe, settle } from './helpers'

describe('query-observer', () => {
  it('[obs-001] mount with empty cache fetches; result is optimistic', async () => {
    const qc = client()
    const fn = controlled()
    const o = observe(qc, { queryKey: ['a'], queryFn: fn.fn })
    expect(o.current.status).toBe('pending')
    expect(o.current.fetchStatus).toBe('fetching')
    expect(o.current.isLoading).toBe(true)
    await settle()
    expect(fn.count).toBe(1)
    await fn.resolveLast('A')
    const last = o.results.at(-1)
    expect(last.status).toBe('success')
    expect(last.data).toBe('A')
    expect(last.isFetching).toBe(false)
  })

  it('[obs-002] fresh cached data is served immediately without fetching', async () => {
    const qc = client()
    const fn = immediate(() => 'A')
    await qc.fetchQuery({ queryKey: ['a'], queryFn: fn.fn })
    const o = observe(qc, { queryKey: ['a'], queryFn: fn.fn, staleTime: 1000 })
    expect(o.current.status).toBe('success')
    expect(o.current.data).toBe('A')
    expect(o.current.isFetching).toBe(false)
    expect(o.current.isStale).toBe(false)
    await settle()
    expect(fn.count).toBe(1)
  })

  it('[obs-003] stale cached data is served immediately and refetched in background', async () => {
    const qc = client()
    qc.setQueryData(['a'], 'A')
    const fn = controlled()
    const o = observe(qc, { queryKey: ['a'], queryFn: fn.fn })
    expect(o.current.status).toBe('success')
    expect(o.current.data).toBe('A')
    expect(o.current.isFetching).toBe(true)
    expect(o.current.isRefetching).toBe(true)
    await settle()
    expect(fn.count).toBe(1)
    await fn.resolveLast('B')
    expect(o.current.data).toBe('B')
    expect(o.current.isFetching).toBe(false)
  })

  it('[obs-004] enabled: false', async () => {
    const qc = client()
    const fn = controlled()
    const o = observe(qc, { queryKey: ['a'], queryFn: fn.fn, enabled: false })
    await settle()
    expect(o.current.status).toBe('pending')
    expect(o.current.fetchStatus).toBe('idle')
    expect(o.current.isLoading).toBe(false)
    expect(o.current.isEnabled).toBe(false)
    expect(o.current.isStale).toBe(false)
    expect(fn.count).toBe(0)
    o.observer.setOptions({ queryKey: ['a'], queryFn: fn.fn, enabled: true })
    await settle()
    expect(fn.count).toBe(1)
    expect(o.current.fetchStatus).toBe('fetching')
  })

  it('[obs-005] select derives data without changing the cache', async () => {
    const qc = client()
    const o = observe(qc, { queryKey: ['a'], queryFn: immediate(() => ({ count: 2 })).fn, select: (d: any) => d.count * 10 })
    await settle()
    expect(o.current.data).toBe(20)
    expect(qc.getQueryData(['a'])).toEqual({ count: 2 })
  })

  it('[obs-006] placeholderData', async () => {
    const qc = client()
    const fn = controlled()
    const o = observe(qc, { queryKey: ['a'], queryFn: fn.fn, placeholderData: 'ph' })
    expect(o.current.status).toBe('success')
    expect(o.current.data).toBe('ph')
    expect(o.current.isPlaceholderData).toBe(true)
    expect(o.current.isFetching).toBe(true)
    expect(qc.getQueryData(['a'])).toBeUndefined()
    await settle()
    await fn.resolveLast('A')
    expect(o.current.data).toBe('A')
    expect(o.current.isPlaceholderData).toBe(false)
  })

  it('[obs-007] refetch() returns the new result', async () => {
    const qc = client()
    const fn = immediate((n) => (n === 0 ? 'A' : 'B'))
    const o = observe(qc, { queryKey: ['a'], queryFn: fn.fn })
    await settle()
    const r = await o.observer.refetch()
    expect(r.data).toBe('B')
    expect(fn.count).toBe(2)
  })

  it('[obs-008] changing the key switches queries', async () => {
    const qc = client()
    const fn = controlled()
    const o = observe(qc, { queryKey: ['a', 1], queryFn: fn.fn })
    await settle()
    await fn.resolveLast('one')
    o.observer.setOptions({ queryKey: ['a', 2], queryFn: fn.fn })
    await settle()
    expect(fn.last().key).toEqual(['a', 2])
    expect(o.current.status).toBe('pending')
    expect(o.current.isFetching).toBe(true)
    expect(o.current.data).toBeUndefined()
    const q1 = qc.getQueryCache().find({ queryKey: ['a', 1] })!
    expect(q1.getObserversCount()).toBe(0)
    expect(q1.state.data).toBe('one')
    await fn.resolveLast('two')
    expect(o.current.data).toBe('two')
  })

  it('[obs-009] listener notifications and unsubscribe', async () => {
    const qc = client()
    const fn = controlled()
    const o = observe(qc, { queryKey: ['a'], queryFn: fn.fn })
    await settle()
    await fn.resolveLast('A')
    const fetchingIdx = o.results.findIndex((r) => r.isFetching)
    const successIdx = o.results.findIndex((r) => r.status === 'success' && r.data === 'A')
    expect(fetchingIdx).toBeGreaterThanOrEqual(0)
    expect(successIdx).toBeGreaterThan(fetchingIdx)
    o.unsubscribe()
    const before = o.results.length
    qc.setQueryData(['a'], 'B')
    await settle()
    expect(o.results.length).toBe(before)
  })

  it('[obs-010] refetchInterval', async () => {
    const qc = client()
    const fn = immediate(() => 'A')
    const o = observe(qc, { queryKey: ['a'], queryFn: fn.fn, refetchInterval: 1000 })
    await settle()
    expect(fn.count).toBe(1)
    await advance(1000)
    expect(fn.count).toBe(2)
    await advance(1000)
    expect(fn.count).toBe(3)
    o.unsubscribe()
    await advance(5000)
    expect(fn.count).toBe(3)
  })

  it('[obs-011] refetchOnMount', async () => {
    const qc = client()
    qc.setQueryData(['a'], 'A')
    const fa = controlled()
    observe(qc, { queryKey: ['a'], queryFn: fa.fn, refetchOnMount: false })
    await settle()
    expect(fa.count).toBe(0)
    qc.setQueryData(['b'], 'B')
    const fb = controlled()
    observe(qc, { queryKey: ['b'], queryFn: fb.fn, staleTime: Infinity, refetchOnMount: 'always' })
    await settle()
    expect(fb.count).toBe(1)
  })

  it('[obs-012] result becomes stale over time without refetching', async () => {
    const qc = client()
    const fn = immediate(() => 'A')
    const o = observe(qc, { queryKey: ['a'], queryFn: fn.fn, staleTime: 1000 })
    await settle()
    expect(o.current.isStale).toBe(false)
    await advance(1001)
    expect(o.results.at(-1).isStale).toBe(true)
    expect(fn.count).toBe(1)
  })

  it('[obs-013] isFetchedAfterMount', async () => {
    const qc = client()
    await qc.fetchQuery({ queryKey: ['a'], queryFn: immediate(() => 'A').fn })
    const fn = controlled()
    const o = observe(qc, { queryKey: ['a'], queryFn: fn.fn })
    await settle()
    expect(o.current.isFetched).toBe(true)
    expect(o.current.isFetchedAfterMount).toBe(false)
    await fn.resolveLast('B')
    expect(o.current.isFetchedAfterMount).toBe(true)
  })

  it('[obs-014] error results', async () => {
    const qc = client()
    const fn = controlled()
    const E = new Error('E')
    const o = observe(qc, { queryKey: ['a'], queryFn: fn.fn, retry: false })
    await settle()
    await fn.rejectLast(E)
    expect(o.current.status).toBe('error')
    expect(o.current.isError).toBe(true)
    expect(o.current.isLoadingError).toBe(true)
    expect(o.current.isRefetchError).toBe(false)
    expect(o.current.error).toBe(E)

    qc.setQueryData(['a'], 'A')
    const E2 = new Error('E2')
    void o.observer.refetch()
    await settle()
    await fn.rejectLast(E2)
    expect(o.current.status).toBe('error')
    expect(o.current.data).toBe('A')
    expect(o.current.isRefetchError).toBe(true)
    expect(o.current.isLoadingError).toBe(false)
  })

  it('[obs-015] staleTime "static"', async () => {
    const qc = client()
    qc.setQueryData(['a'], 'A')
    const fn = controlled()
    const o = observe(qc, { queryKey: ['a'], queryFn: fn.fn, staleTime: 'static', refetchOnMount: 'always' })
    await settle()
    expect(fn.count).toBe(0)
    expect(o.current.isStale).toBe(false)
    await qc.invalidateQueries()
    await settle()
    expect(fn.count).toBe(0)
    expect(o.current.isStale).toBe(false)
  })
})
